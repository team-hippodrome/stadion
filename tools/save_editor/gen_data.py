#!/usr/bin/env python3
"""Generates stadium_save/gamedata.py from the US ROM and the decomp sources.

usage: gen_data.py <rom.z64> <decomp src dir> [out.py]

Extracted:
- species / move / type / item names: textdata BinArchive at ROM 0x783760 (US), string tables 0x24, 0x25, 0x26, 0x27
  (layout as described in stadion/tools/patch_textdata.py)
- per-species data (dex order): D_80070FA0 in src/gb_data.c (base HP/Atk/Def/Spd/Spc, Gen 1 types, catch rate,
  base experience, starting moves, growth rate at +0x0E: 0 medium fast, 3 medium slow, 4 fast, 5 slow (formulas in Pokemon_ExpForLevel))
- Gen 1 internal species index <-> dex tables: gDexToInternalIndex / gInternalIndexToDex in src/pokemon_stats.c
- move data: gMoveData in src/gb_data.c (id, effect, power, type, accuracy, PP)
- Game Boy character set -> N64 font byte: D_80073030 in src/gb_data.c (used by Text_UntranscodeName)
"""
import re
import struct
import sys

TEXTDATA_US = (0x783760, 0x798CD0)


def text_tables(rom):
    blob = rom[TEXTDATA_US[0]:TEXTDATA_US[1]]
    n = struct.unpack_from(">I", blob, 12)[0]
    files = [blob[o:o + s] for o, s in (struct.unpack_from(">II", blob, 16 + 16 * i) for i in range(n))]

    def table(f):
        k = struct.unpack_from(">I", f, 0)[0]
        return [f[o:f.index(b"\0", o)].decode("latin-1") for o in struct.unpack_from(f">{k}I", f, 4)]

    return table


def c_bytes(src, start_pat, end_pat="};"):
    i = src.index(start_pat)
    j = src.index(end_pat, i)
    body = src[i + len(start_pat):j]
    # US (non REV2) branch only
    if "#if" in body:
        body = body.split("#else", 1)[1].split("#endif", 1)[0]
    return [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})\b", body)]


def main():
    rom = open(sys.argv[1], "rb").read()
    src_dir = sys.argv[2]
    out = sys.argv[3] if len(sys.argv) > 3 else __file__.rsplit("/", 1)[0] + "/stadium_save/gamedata.py"
    blob = rom[TEXTDATA_US[0]:TEXTDATA_US[1]]
    n = struct.unpack_from(">I", blob, 12)[0]
    files = [blob[o:o + s] for o, s in (struct.unpack_from(">II", blob, 16 + 16 * i) for i in range(n))]

    def table(i):
        f = files[i]
        k = struct.unpack_from(">I", f, 0)[0]
        return [f[o:f.index(b"\0", o)].decode("latin-1") for o in struct.unpack_from(f">{k}I", f, 4)]

    # the N64 font draws 0xA9/0xBE as the male/female signs and 0xBC/0xBD as the PK/MN ligatures
    fix = lambda names: [n.replace("\u00a9", "\u2642").replace("\u00be", "\u2640").replace("\u00bc", "<PK>")
                         .replace("\u00bd", "<MN>") for n in names]
    species = fix(table(0x24))
    moves = fix(table(0x25))
    types16 = table(0x26)
    items = fix(table(0x27))
    # TM/HM ids have no string (Text_GetTmHmName formats them): 0xC4..0xC8 HM01-05, 0xC9..0xFA TM01-50
    items += [""] * (0xFA - len(items))
    for k in range(5):
        items[0xC4 + k - 1] = items[0xC4 + k - 1] or "HM%02d" % (k + 1)
    for k in range(50):
        items[0xC9 + k - 1] = items[0xC9 + k - 1] or "TM%02d" % (k + 1)

    gb = open(src_dir + "/gb_data.c", encoding="utf-8").read()
    ps = open(src_dir + "/pokemon_stats.c", encoding="utf-8").read()

    rows = []
    i = gb.index("D_80070FA0[152] = {")
    j = gb.index("};", i)
    for line in gb[i:j].splitlines()[1:]:
        vals = [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})\b", line)]
        if len(vals) == 0x17:
            rows.append(vals)
    packed = c_bytes(ps, "u8 D_80073230[0x420] = {")
    dex_to_index = packed[0x37:0x37 + 152]
    index_to_dex = packed[0xCF:0xCF + 192]
    gb_charset = c_bytes(gb, "s8 D_80073030[0x100] = {")
    n64_to_gb = c_bytes(gb, "u8 D_80073130[0x100] = {")
    i = gb.index("MoveData gMoveData[165] = {")
    mv = [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})\b", gb[i:gb.index("};", i)])]
    move_data = [tuple(mv[k:k + 6]) for k in range(0, len(mv), 6)]
    assert len(move_data) == 165 and all(m[0] == k + 1 for k, m in enumerate(move_data))
    assert len(gb_charset) == 256 and len(n64_to_gb) == 256 and len(rows) >= 151

    # Gen 1 type ids -> names: table 0x26 lists ids 0..8 then 0x14..0x1A
    type_names = {}
    for k in range(9):
        type_names[k] = types16[k]
    for k in range(7):
        type_names[0x14 + k] = types16[9 + k].strip()
    type_names[6] = None  # unused id (Bird); table 0x26 repeats "Flying" there

    with open(out, "w", encoding="utf-8") as f:
        f.write('"""Generated by tools/save_editor/gen_data.py from the US ROM text tables and decomp data. Do not edit."""\n\n')
        f.write("# dex number (1..151) -> name; index 0 unused\n")
        f.write("SPECIES = %r\n\n" % ([""] + species))
        f.write("# move id (1..165) -> name; index 0 = no move\n")
        f.write("MOVES = %r\n\n" % ([""] + moves))
        f.write("# move id -> (effect, power, type, accuracy 0..255, base PP) from gMoveData; index 0 unused\n")
        f.write("MOVE_DATA = [None,\n")
        for m in move_data:
            f.write("    %r,\n" % (m[1:],))
        f.write("]\n\n")
        f.write("# Gen 1 item id -> name (string table 0x27 index id-1; '' = unnamed)\n")
        f.write("ITEMS = %r\n\n" % ([""] + items))
        f.write("# Gen 1 type id -> name\n")
        f.write("TYPES = %r\n\n" % type_names)
        f.write("# dex -> Gen 1 internal species index (gDexToInternalIndex); 0 = none\n")
        f.write("DEX_TO_INDEX = %r\n\n" % dex_to_index)
        f.write("# Gen 1 internal species index -> dex (gInternalIndexToDex); 152 = invalid/MissingNo\n")
        f.write("INDEX_TO_DEX = %r\n\n" % index_to_dex)
        f.write("# dex -> (hp, atk, def, spd, spc, type1, type2, catch_rate, base_exp, (moves), growth)\n")
        f.write("BASE = [None,\n")
        for r in rows[:151]:
            f.write("    (%d, %d, %d, %d, %d, %d, %d, %d, %d, (%d, %d, %d, %d), %d),\n" % (
                r[1], r[2], r[3], r[4], r[5], r[6], r[7], r[8], r[9], r[10], r[11], r[12], r[13], r[0x0E]))
        f.write("]\n\n")
        f.write("# Game Boy character byte -> N64 font byte (D_80073030); 0x20 = no glyph\n")
        f.write("GB_TO_N64 = bytes(%r)\n\n" % bytes(gb_charset))
        f.write("# N64 font byte -> Game Boy character byte (D_80073130, US); 0 = none\n")
        f.write("N64_TO_GB = bytes(%r)\n" % bytes(n64_to_gb))
    print("wrote", out)


if __name__ == "__main__":
    main()
