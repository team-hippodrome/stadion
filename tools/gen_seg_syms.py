#!/usr/bin/env python3 -I
"""Writes src/port/generated/seg_syms.c: for every European ROM, the segment addresses (D_2001A20 style, an image
inside a UI archive loaded at a segment) that the decomp links to a different value in that ROM's build than in US
Rev 2, the version the port's code is compiled as.

The French, German, Spanish and Italian releases rearranged several UI archives: an image the US code finds at
0x2001A20 sits at another offset there. The decomp's matching builds of those releases compile the same C and link
these names to their own values (linker_scripts/<version>/undefined_syms.ld). The port compiles the code once, so the
game wraps each such use in PORT_SEGSYM() (StadionPort.h), which looks the Rev 2 value up here for the loaded ROM.
Offsets only; no ROM data.

Usage: tools/gen_seg_syms.py   (reads the decomp's linker scripts; decomp_paths.DECOMP)"""
import pathlib, re, sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import decomp_paths

ROOT = decomp_paths.ROOT
OUT = ROOT / "src/port/generated/seg_syms.c"
CODE = decomp_paths.CODE_VERSION
VERSIONS = {
    "eu": "PORT_ROM_EU",
    "eu_rev1": "PORT_ROM_EU_REV1",
    "fr": "PORT_ROM_FR",
    "de": "PORT_ROM_DE",
    "es": "PORT_ROM_ES",
    "it": "PORT_ROM_IT",
}
PROVIDE = re.compile(r"PROVIDE\((D_0?[0-9A-F]{7})\s*=\s*0x([0-9A-Fa-f]+)\)")


def provides(version):
    path = decomp_paths.DECOMP / "linker_scripts" / version / "undefined_syms.ld"
    out = {}
    for m in PROVIDE.finditer(path.read_text()):
        value = int(m.group(2), 16)
        if 0x01000000 <= value < 0x10000000:  # segment addresses only
            out[m.group(1)] = value
    return out


def main():
    code = provides(CODE)
    lines = ["// Generated by tools/gen_seg_syms.py from the decomp's linker scripts. Do not edit.",
             "// Segment addresses only; no ROM data.", '#include "seg_syms.h"', ""]
    tables = []
    for ver, enum in VERSIONS.items():
        syms = provides(ver)
        rows = {}
        for name, value in syms.items():
            if name in code and code[name] != value:
                old = rows.get(code[name])
                if old is not None and old[1] != value:
                    sys.exit(f"{ver}: {name} and {old[0]} share Rev 2 value 0x{code[name]:X} but link differently")
                rows[code[name]] = (name, value)
        if not rows:
            continue
        lines.append(f"static const PortSegSym sSegSyms_{ver}[] = {{")
        for rev2 in sorted(rows):
            name, value = rows[rev2]
            lines.append(f"    {{ 0x{rev2:07X}, 0x{value:07X} }}, // {name}")
        lines.append("};")
        tables.append((enum, ver, len(rows)))
        print(f"{ver}: {len(rows)} segment addresses", file=sys.stderr)
    lines.append("")
    lines.append("const PortSegSymTable gPortSegSymTables[] = {")
    for enum, ver, n in tables:
        lines.append(f"    {{ {enum}, sSegSyms_{ver}, {n} }},")
    lines.append("};")
    lines.append(f"const unsigned gPortSegSymTableCount = {len(tables)};")
    OUT.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
