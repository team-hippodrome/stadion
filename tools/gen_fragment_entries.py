#!/usr/bin/env python3 -I
"""Builds the fragment entry table: for every fragment, its ROM offset (key used by Fragment_Load), link-time
base address and the C function the fragment header jumps to. Fragment code is statically linked in the port,
so loading a fragment only needs to find that function."""
import re, struct, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
# the unmodified decomp checkout and build the game is patched from (PORT_DECOMP_DIR, default ../pokestadium)
dec = pathlib.Path(__import__("os").environ.get("PORT_DECOMP_DIR", root.parent / "pokestadium"))
mp = (dec / "build/pokestadium-us.map").read_text(errors="replace").split("\n")
syms = {}   # address -> first symbol name seen
sympat = re.compile(r"^\s+0x([0-9a-f]{8,16})\s+([A-Za-z_]\w*)\s*(?:=.*)?$")
frags = {}
cur = None
for i, l in enumerate(mp):
    m = re.match(r"^\s+0x([0-9a-f]{8,16})\s+(fragment\d+)_ROM_START\s*=", l)
    if m:
        frags.setdefault(m.group(2), {})["rom"] = int(m.group(1), 16)
    m = re.match(r"^\s+0x([0-9a-f]{8,16})\s+(fragment\d+)_TEXT_START\s*=", l)
    if m:
        name = m.group(2)
        frags.setdefault(name, {})["text"] = int(m.group(1), 16)
        # the next object line names the header file
        for j in range(i + 1, i + 4):
            h = re.search(r"build/asm/us/data/(\S+?)_header\.o", mp[j])
            if h:
                frags[name]["header"] = h.group(1)
                break
    s = sympat.match(l)
    if s:
        syms.setdefault(int(s.group(1), 16), s.group(2))
# entry functions must exist in the compiled game (a table disassembled as code has a func_ symbol but no C function)
import subprocess
# C symbols carry a leading underscore in Mach-O (macOS) object files, not in ELF (Linux)
CPFX = "_" if __import__("sys").platform == "darwin" else ""
_nm = subprocess.run(["nm", "-g", str(root / "build/libstadium_game.a")], capture_output=True, text=True).stdout
defined = {l.split()[2][len(CPFX):] for l in _nm.splitlines() if len(l.split()) == 3 and l.split()[1] in "TtDd"}
rows, missing = [], []
for name, f in sorted(frags.items(), key=lambda kv: int(kv[0][8:])):
    if "rom" not in f or "text" not in f or "header" not in f:
        missing.append(name); continue
    hb = dec / f"assets/us/{f['header']}_header.textbin.bin"
    if not hb.exists():
        # header binary name differs (e.g. *_header.textbin.bin under assets/us/<dir>)
        cand = list((dec / "assets/us").rglob(pathlib.Path(f["header"]).name + "_header.textbin.bin"))
        if not cand:
            missing.append(name + "(no header bin)"); continue
        hb = cand[0]
    inst = struct.unpack(">I", hb.read_bytes()[:4])[0]
    target = ((inst & 0x03FFFFFF) << 2) | 0x80000000 | (f["text"] & 0x70000000)
    sym = syms.get(target)
    if sym is None:
        missing.append(name + f"(no sym @0x{target:X})"); continue
    if sym not in defined:
        missing.append(name + f"({sym} not in the compiled game)"); continue
    rows.append((name, f["rom"], f["text"], sym))
out = ["// Generated by tools/gen_fragment_entries.py from the decomp map and fragment header words.",
       "#include \"global.h\"", ""]
for _, _, _, sym in rows:
    out.append(f"extern void {sym}();")
out += ["", "struct PortFragmentEntry { unsigned romStart; unsigned textStart; void* entry; const char* name; };",
        "const struct PortFragmentEntry gPortFragmentEntries[] = {"]
for name, rom, text, sym in rows:
    out.append(f"    {{ 0x{rom:X}, 0x{text:X}, (void*){sym}, \"{name}\" }},")
out += ["    { 0, 0, 0, 0 },", "};", ""]
(root / "src/port/generated/port_fragment_entries.c").write_text("\n".join(out))
print(len(rows), "fragments; missing:", missing)
