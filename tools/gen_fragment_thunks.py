#!/usr/bin/env python3 -I
"""Web build: writes <out>/fragment_thunks.c, a thunk with the exact type of FragmentEntry (s32 (*)(s32, intptr_t),
game/src/memmap.h) for each fragment entry of src/port/generated/port_fragment_entries.c, and
Port_FragmentCallable(), which maps an entry to its thunk (game/src/jpeg_stream.c, Fragment_Load).

The game calls every fragment's entry through FragmentEntry, but the entries are defined with other signatures
(s32 f(s32, s32), void f(void), ...). Native code does not mind; WebAssembly traps on a call whose type differs from
the function's. The thunk calls the entry with its own signature: the first two arguments passed on, further ones zero
(on the N64 they were whatever the registers held), the result 0 where the entry returns nothing.

Usage: gen_fragment_thunks.py <game/src> <port_fragment_entries.c> <out dir>"""
import pathlib
import re
import sys

src, entries_file, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]), pathlib.Path(sys.argv[3])
names = re.findall(r'\(void\*\)(\w+), "fragment', entries_file.read_text())

# function pointer typedefs (pointer-sized results/arguments)
fnptr_typedefs = set()
for h in list(src.rglob("*.h")) + list((src.parent / "include").rglob("*.h")):
    fnptr_typedefs.update(re.findall(r"typedef[^;{]*\(\s*\*\s*(\w+)\s*\)\s*\(", h.read_text(errors="replace")))

defs = {}
for f in src.rglob("*.c"):
    for m in re.finditer(r"^(?:static\s+)?([A-Za-z_][\w \*]*?)\b(\w+)\(([^)]*)\)\s*\{", f.read_text(errors="replace"), re.M):
        defs.setdefault(m.group(2), (m.group(1).strip(), m.group(3)))

INT32 = {"s8", "u8", "s16", "u16", "s32", "u32", "int", "char", "short", "unsigned", "signed", "bool", "u8*"}


def c_type(t):
    """The type to call with: what matters is the WebAssembly type (i32, i64, f32, f64)."""
    t = re.sub(r"\b(UNUSED|const|volatile|struct|union|enum|unsigned|signed)\b", " ", t).strip()
    t = re.sub(r"\s+\w+$", "", t) if not t.endswith("*") and len(t.split()) > 1 else t  # drop the parameter name
    if "*" in t or t in fnptr_typedefs:
        return "void*"
    if t in ("f32", "float"):
        return "float"
    if t in ("f64", "double"):
        return "double"
    if t in ("s64", "u64", "long", "intptr_t", "uintptr_t", "size_t", "OSTime"):
        return "int64_t"
    if t == "void":
        return "void"
    return "int32_t"  # s32, u16, enums, ... (integer types up to 32 bits)


lines = ["// Generated by tools/gen_fragment_thunks.py (web build): FragmentEntry-typed thunks for the fragment entries.",
         "#include <stdint.h>", ""]
cases = []
for n in names:
    if n not in defs:
        sys.exit(f"gen_fragment_thunks.py: no definition of {n} in {src}")
    ret, params = defs[n]
    ret_t = c_type(ret)
    plist = [] if params.strip() in ("", "void") else [p.strip() for p in re.split(r",(?![^()]*\))", params)]
    ptypes = []
    for p in plist:
        # a parameter is "<type> <name>": the name is the last word unless the type ends in '*'
        m = re.match(r"(.*?)(\w+)\s*$", p)
        ptypes.append(c_type(m.group(1) if m and m.group(1).strip() else p))
    args = []
    for i, pt in enumerate(ptypes):
        if i < 2:
            v = f"a{i}"
            args.append(f"({pt})(intptr_t){v}" if pt == "void*" else f"({pt}){v}")
        else:
            args.append(f"({pt})0")
    proto = f"{ret_t} (*)({', '.join(ptypes) or 'void'})"
    call = f"(({proto}){n})({', '.join(args)})"
    lines.append(f"extern void {n}();")
    if ret_t == "void":
        body = f"{call};\n    return 0;"
    elif ret_t == "void*":
        body = f"return (int32_t)(intptr_t){call};"
    else:
        body = f"return (int32_t){call};"
    lines.append(f"static int32_t thunk_{n}(int32_t a0, intptr_t a1) {{\n    (void)a0;\n    (void)a1;\n    {body}\n}}")
    cases.append(f"    if (entry == (void*){n}) {{\n        return (void*)thunk_{n};\n    }}")
lines.append("")
lines.append("void* Port_FragmentCallable(void* entry) {")
lines += cases
lines.append("    return entry;")
lines.append("}")
out.mkdir(parents=True, exist_ok=True)
(out / "fragment_thunks.c").write_text("\n".join(lines) + "\n")
