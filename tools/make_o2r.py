#!/usr/bin/env python3 -I
"""Packs the port's runtime resources into build/stadion.o2r (a zip libultraship opens as an archive):
the Fast3D shader sources, the shader warm-up list, the launcher pictures and a port version marker. Game data is not in here; it is read from the ROM."""
import zipfile, pathlib, sys
root = pathlib.Path(__file__).resolve().parent.parent
args = sys.argv[1:]
# --c <file>: also write the archive as a C array (gPortO2r, gPortO2rSize), the copy built into the executable
c_out = None
if "--c" in args:
    i = args.index("--c")
    c_out = pathlib.Path(args[i + 1])
    del args[i:i + 2]
# --add <archive name>=<file>: include generated web fragment ranges.
extra = [value.split("=", 1) for flag, value in zip(args[1:], args[2:]) if flag == "--add"]
out = pathlib.Path(args[0]) if args else root / "build/stadion.o2r"
out.parent.mkdir(parents=True, exist_ok=True)
with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
    z.writestr("portVersion", b"\x00\x00\x00\x01\x00\x00")
    shaders = root / "libultraship/src/fast/shaders"
    for p in sorted(shaders.rglob("*")):
        if p.is_file():
            data = p.read_bytes()
            if p.suffix == ".metal":
                # The macOS 27 Metal compiler rejects address-space qualifiers on by-value helper parameters
                # ("parameter may not be qualified with an address space"); drop them there. References keep
                # theirs: older Metal language versions (binaries built with an older SDK, e.g. the macOS 15 CI
                # runner) require it ("reference type must have explicit address space qualifier").
                import re
                text = data.decode()
                text = re.sub(r"\bthread (const \w+(?:<\w+>)? )(?=\w)", r"\1", text)
                data = text.encode()
            z.writestr("shaders/" + p.relative_to(shaders).as_posix(), data)
    # the shader programs built ahead while the launcher shows (src/port/shader_warmup.cpp, tools/shader_list.py)
    z.write(root / "src/port/shader_warmup.txt", "port/shader_warmup.txt")
    # Pipeline states recorded in to_battle, tour_fb, tour_galenl3 and tour_mg_dynamo.
    z.write(root / "src/port/vulkan_pipeline_warmup.txt", "port/vulkan_pipeline_warmup.txt")
    # the port's own strings in every language (translation/port.csv: the first-boot language prompt,
    # src/port/language_prompt.cpp) and the fonts that draw them (hippodrome-utils' assets/font, with their licences)
    z.write(root / "translation/port.csv", "translation/port.csv")
    # the translations of each source ROM's text the game draws in the chosen language (src/port/text_lookup.cpp;
    # translation/README.md). Only the tables: they hold no ROM text.
    for src in ("en", "es", "fr", "de", "it", "jp"):
        if (root / f"translation/{src}.csv").exists():
            z.write(root / f"translation/{src}.csv", f"translation/{src}.csv")
    # the Japanese ROM's COM nicknames and its text in kanji, for the Nintendo Cups taken from a Japanese ROM beside a
    # western one (src/port/nintendo_cup.cpp)
    # the announcer's subtitles: transcriptions of each dub's voice lines and their translations (src/port/announcer.cpp)
    if (root / "translation/subtitles.csv").exists():
        z.write(root / "translation/subtitles.csv", "translation/subtitles.csv")
    for name in ("jp_localized", "kanji"):
        if (root / f"translation/{name}.csv").exists():
            z.write(root / f"translation/{name}.csv", f"translation/{name}.csv")
    fonts = root / "hippodrome-utils/assets/font"
    for name in ("pop_subset.ttf", "unifont_subset.otf", "unifont_subset.hex", "LICENSE-pop.txt",
                 "LICENSE-unifont.txt"):
        z.write(fonts / name, "fonts/" + name)
    # launcher pictures (cartridges, N64), shown by src/port/launcher.cpp
    for p in sorted((root / "tools/launcher/assets").glob("*.png")):
        z.write(p, "textures/launcher/" + p.name)
    for name, path in extra:
        z.write(path, name)
print("wrote", out)
if c_out is not None:
    data = out.read_bytes()
    lines = [",".join(str(b) for b in data[i:i + 32]) for i in range(0, len(data), 32)]
    c_out.parent.mkdir(parents=True, exist_ok=True)
    c_out.write_text("// Generated by tools/make_o2r.py: stadion.o2r, built into the executable (src/port/Engine.cpp)\n"
                     "#include <stddef.h>\n"
                     "const unsigned char gPortO2r[] = {\n" + ",\n".join(lines) + "\n};\n"
                     "const size_t gPortO2rSize = sizeof(gPortO2r);\n")
    print("wrote", c_out)
