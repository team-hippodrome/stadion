#!/usr/bin/env python3 -I
"""Writes src/port/generated/rom_layouts.c: for every ROM the port accepts, where the pieces of the US Rev 2 ROM (the
version the port's code is compiled as, decomp_paths.CODE_VERSION) are in that ROM, and where the code moved.

The game code addresses ROM by Rev 2 offsets (link-time constants in abs_syms.S, literals in the C). For another ROM
src/port/rom_version.cpp maps each Rev 2 offset into it through the segment table below: the segment that holds the
offset, moved by that segment's delta. The tables are offsets and lengths read from the decomp's link maps (one build
per version: `make extract VERSION=<v> && make VERSION=<v>` in the decomp); they hold no ROM bytes.

Code addresses: the fragment images the game loads from the ROM are that version's code, so a jump read from one (the
particle library's trampolines, jpeg_stream.c Port_ResolveCode) targets that version's link address. The second
table maps those addresses, per fragment, to the Rev 2 address of the same symbol.

Usage: tools/gen_rom_layouts.py   (reads decomp_paths.MAPS)"""
import pathlib, re, sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import decomp_paths

ROOT = decomp_paths.ROOT
OUT = ROOT / "src/port/generated/rom_layouts.c"
CODE = decomp_paths.CODE_VERSION
# version -> enum name in rom_layouts.h (rom_version.cpp recognizes each ROM by its SHA-1)
VERSIONS = {
    "us": "PORT_ROM_US",
    "us_rev1": "PORT_ROM_US_REV1",
    "us_rev2": "PORT_ROM_US_REV2",
    "eu": "PORT_ROM_EU",
    "eu_rev1": "PORT_ROM_EU_REV1",
    "fr": "PORT_ROM_FR",
    "de": "PORT_ROM_DE",
    "es": "PORT_ROM_ES",
    "it": "PORT_ROM_IT",
}
SYM = re.compile(r"^\s+0x([0-9a-f]{8,16})\s+(?:PROVIDE \()?([A-Za-z_]\w*)\s*(?:=.*)?$")


def symbols(path):
    out = {}
    for line in path.read_text(errors="replace").splitlines():
        m = SYM.match(line)
        if m:
            out.setdefault(m.group(2), int(m.group(1), 16))
    return out


def segments(syms):
    """name -> (rom start, rom end) for every piece the linker script places in ROM"""
    out = {}
    for name, start in syms.items():
        if name.endswith("_ROM_START"):
            base = name[:-len("_ROM_START")]
            end = syms.get(base + "_ROM_END")
            if end is not None and end >= start:
                out[base] = (start, end)
    return out


def code_ranges(syms):
    """(text start, text end, fragment name or "") for the main segment and every fragment"""
    out = []
    for name, start in syms.items():
        m = re.fullmatch(r"(fragment\d+)_TEXT_START", name)
        if m and m.group(1) + "_TEXT_END" in syms:
            out.append((start, syms[m.group(1) + "_TEXT_END"], m.group(1)))
    out.append((syms["text_VRAM"], syms["text_VRAM_END"], ""))  # the main segment
    return out


def main_segment_rows(code, syms):
    """The main segment (uncompressed code and data, read in place: e.g. the audio microcode's tables) moves piece by
    piece when a version's code grows, so it gets one row per run of symbols that moved by the same amount."""
    def rom_of(s, addr):
        return s["text_ROM_START"] + addr - s["text_VRAM"]
    anchors = {}
    for name, gaddr in code.items():
        vaddr = syms.get(name)
        if vaddr is None or name.endswith(("_VRAM", "_VRAM_END")):
            continue
        if code["text_VRAM"] <= gaddr < code["text_VRAM_END"] and syms["text_VRAM"] <= vaddr < syms["text_VRAM_END"]:
            anchors.setdefault(rom_of(code, gaddr), rom_of(syms, vaddr))
    gstart, gend = code["text_ROM_START"], code["text_ROM_END"]
    anchors.setdefault(gstart, syms["text_ROM_START"])
    pts = sorted(anchors.items())
    rows, run = [], None  # run: [game start, version start, delta]
    for g, v in pts:
        if run is None or v - g != run[2]:
            if run is not None:
                rows.append((run[0], g, run[1], run[1] + g - run[0], "text"))
            run = [g, v, v - g]
    rows.append((run[0], gend, run[1], run[1] + gend - run[0], "text"))
    return rows


def owner(ranges, addr):
    for lo, hi, frag in ranges:
        if lo <= addr < hi:
            return frag
    return None


def main():
    maps = {v: symbols(p) for v, p in decomp_paths.MAPS.items()}
    code = maps[CODE]
    code_segs = segments(code)
    code_code = code_ranges(code)
    lines = ["// Generated by tools/gen_rom_layouts.py from the decomp's link maps of each version. Do not edit.",
             "// Offsets and link addresses only; no ROM data.", "#include \"rom_layouts.h\"", ""]
    tables = []
    for ver, enum in VERSIONS.items():
        if ver == CODE:
            tables.append((ver, enum, 0, 0))
            continue
        syms = maps[ver]
        segs = segments(syms)
        rows = sorted((code_segs[n][0], code_segs[n][1], segs[n][0], segs[n][1], n) for n in code_segs if n in segs
                      if n != "text")
        rows = sorted(rows + main_segment_rows(code, syms))
        lines.append(f"static const PortRomSegment sSegments_{ver}[] = {{")
        for gs, ge, vs, ve, n in rows:
            lines.append(f"    {{ 0x{gs:07X}, 0x{ge:07X}, 0x{vs:07X}, 0x{ve:07X} }}, // {n}")
        lines.append("};")
        # code addresses: symbols inside a text range of both builds, in the same fragment, at a different address
        ver_code = code_ranges(syms)
        frag_rom = {n: code_segs[n][0] for n in code_segs if re.fullmatch(r"fragment\d+", n)}
        moved = {}
        for name, vaddr in syms.items():
            gaddr = code.get(name)
            if gaddr is None or vaddr == gaddr or vaddr < 0x80000000 or gaddr < 0x80000000:
                continue
            fv, fg = owner(ver_code, vaddr), owner(code_code, gaddr)
            if fv is None or fv != fg:
                continue
            key = (frag_rom.get(fg, 0) if fg else 0, vaddr)
            moved.setdefault(key, gaddr)
        lines.append(f"static const PortCodeMove sCodeMoves_{ver}[] = {{")
        for (rom, vaddr), gaddr in sorted(moved.items()):
            lines.append(f"    {{ 0x{rom:X}, 0x{vaddr:08X}, 0x{gaddr:08X} }},")
        lines.append("};")
        lines.append("")
        tables.append((ver, enum, len(rows), len(moved)))
    lines.append("const PortRomLayout gPortRomLayouts[] = {")
    for ver, enum, nseg, nmove in tables:
        if ver == CODE:
            lines.append(f"    {{ {enum}, NULL, 0, NULL, 0 }}, // the code's own layout: no mapping")
        else:
            lines.append(f"    {{ {enum}, sSegments_{ver}, {nseg}, sCodeMoves_{ver}, {nmove} }},")
    lines.append("};")
    lines.append(f"const unsigned gPortRomLayoutCount = {len(tables)};")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{OUT.relative_to(ROOT)}: " + ", ".join(f"{v} {n} segments {m} code moves" for v, _, n, m in tables))


if __name__ == "__main__":
    main()
