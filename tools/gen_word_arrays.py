#!/usr/bin/env python3 -I
"""Lists the game's C arrays of 16/32-bit words (u16/s16/u32/s32 NAME[] = {...}) for the renderer.

On the N64 such arrays sit in memory big-endian, and the RDP reads textures/palettes from them byte by byte; on the
host they are little-endian. The renderer (Fast3D TMEM loads) looks up a texture source address by symbol name and
swaps the copied bytes when it lies in one of these arrays.

Usage: tools/gen_word_arrays.py <game/src> <out.c>
"""
import os, re, sys

PAT = re.compile(r"^(?:static\s+)?(?:const\s+)?(u16|s16|u32|s32)\s+([A-Za-z_][A-Za-z0-9_]*)\s*\[[^\]]*\]\s*=\s*\{", re.M)


def main():
    src, out = sys.argv[1], sys.argv[2]
    found = {}
    for root, _, files in os.walk(src):
        for f in files:
            if not f.endswith(".c"):
                continue
            text = open(os.path.join(root, f), errors="replace").read()
            for m in PAT.finditer(text):
                found[m.group(2)] = 2 if m.group(1) in ("u16", "s16") else 4
    names = sorted(found)
    lines = ["// generated by tools/gen_word_arrays.py: C arrays of 16/32-bit words (see there)\n",
             "#include <stddef.h>\n",
             "struct PortWordArray { const char* name; int size; };\n",
             "const struct PortWordArray gPortWordArrays[] = {\n"]
    for n in names:
        lines.append("    { \"%s\", %d },\n" % (n, found[n]))
    lines.append("};\n")
    lines.append("const size_t gPortWordArrayCount = %d;\n" % len(names))
    text = "".join(lines)
    if not os.path.exists(out) or open(out).read() != text:
        open(out, "w").write(text)
    print("%d word arrays" % len(names))


if __name__ == "__main__":
    main()
