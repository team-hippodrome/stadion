#!/usr/bin/env python3 -I
"""Link-address -> function table, so code pointers stored as 32-bit N64 addresses in ROM data (geo-layout callbacks,
dispatch tables) can be turned back into host function pointers. Fragments share link addresses, so each entry
carries the ROM offset of the fragment it belongs to (0 for the always-resident main segment)."""
import re, subprocess, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
# the unmodified decomp checkout and build the game is patched from (PORT_DECOMP_DIR, default ../pokestadium)
decomp = pathlib.Path(__import__("os").environ.get("PORT_DECOMP_DIR", root.parent / "pokestadium"))
mp = (decomp / "build/pokestadium-us.map").read_text(errors="replace").split("\n")
sympat = re.compile(r"^\s+0x([0-9a-f]{8,16})\s+([A-Za-z_]\w*)\s*(?:=.*)?$")
# fragment ranges
frags = {}
for l in mp:
    m = re.match(r"^\s+0x([0-9a-f]{8,16})\s+(fragment\d+)_(ROM_START|TEXT_START|TEXT_END)\s*=", l)
    if m: frags.setdefault(m.group(2), {})[m.group(3)] = int(m.group(1), 16)
ranges = sorted((f["TEXT_START"], f["TEXT_END"], f["ROM_START"]) for f in frags.values() if len(f) == 3)
syms = {}
for l in mp:
    m = sympat.match(l)
    if m: syms.setdefault(m.group(2), int(m.group(1), 16))
# C symbols carry a leading underscore in Mach-O (macOS) object files, not in ELF (Linux)
CPFX = "_" if __import__("sys").platform == "darwin" else ""
lib = root / "build/libstadium_game.a"
nm = subprocess.run(["nm", "-g", str(lib)], capture_output=True, text=True).stdout
defined = set()
for l in nm.splitlines():
    f = l.split()
    if len(f) == 3 and f[1] == "T": defined.add(f[2][len(CPFX):])
rows = []
for name in sorted(defined):
    a = syms.get(name)
    if a is None or a < 0x80000000: continue
    rom = 0
    if a >= 0x81000000:
        hit = [r for r in ranges if r[0] <= a < r[1]]
        if not hit: continue
        rom = hit[0][2]
    rows.append((rom, a, name))
rows.sort()
out = ["// Generated by tools/gen_func_table.py (decomp map + symbols defined in libstadium_game.a).", "#include <stddef.h>",
       "// PORT_ASM_NAME: the C symbol of a function (Mach-O adds a leading underscore; ELF and 64-bit COFF do not)",
       "#if defined(__APPLE__)", "#define PORT_ASM_NAME(n) \"_\" n", "#else", "#define PORT_ASM_NAME(n) n", "#endif", ""]
for i, (_, _, n) in enumerate(rows): out.append(f"extern void port_fn_{i}() __asm__(PORT_ASM_NAME(\"{n}\"));")
out += ["", "struct PortFuncEntry { unsigned rom; unsigned addr; void* fn; };", "const struct PortFuncEntry gPortFuncTable[] = {"]
for i, (rom, a, n) in enumerate(rows): out.append(f"    {{ 0x{rom:X}, 0x{a:X}, (void*)port_fn_{i} }},")
out += ["};", f"const unsigned gPortFuncTableCount = {len(rows)};", ""]
(root / "src/port/generated/port_func_table.c").write_text("\n".join(out))
print(len(rows), "functions")
