#!/usr/bin/env python3 -I
"""Per-fragment data sections, so a fragment's static data starts fresh each time the game loads it.

On the N64 a fragment's code and data are DMA'd from ROM into a slot every time the game loads it: its .data starts
from the ROM image and its .bss from zero. The port links all fragment code statically, so their globals and static
locals would otherwise keep whatever the previous visit left (e.g. the hub's closing-iris state made the area-select
screen black after returning from an area).

This script writes, for each game/src/fragments/<dir> that holds a fragment entry function (port_fragment_entries.c):
  <out>/frag_sect/<dir>.h       #pragma clang section putting the dir's writable data in __DATA,__fdNN / __fbNN
  <out>/frag_sections.cmake     set_source_files_properties(... -include <dir>.h) for the dir's sources
  <out>/frag_sections.c         the table {entry function, data section, bss section}, a startup snapshot of the
                                data sections and Port_FragmentResetData(entry), called by Fragment_Load
Usage: tools/gen_frag_sections.py <game/src> <out dir>
"""
import os, re, sys


def main():
    src, out = sys.argv[1], sys.argv[2]
    entries_c = open(os.path.join(src, "port_fragment_entries.c")).read()
    entries = re.findall(r'\{\s*0x[0-9A-Fa-f]+,\s*0x[0-9A-Fa-f]+,\s*\(void\*\)(\w+),\s*"\w+"\s*\}', entries_c)
    frag_root = os.path.join(src, "fragments")
    dirs = sorted(d for d in os.listdir(frag_root) if os.path.isdir(os.path.join(frag_root, d)))
    owner = {}  # entry function -> dir
    files = {}
    for d in dirs:
        files[d] = sorted(f for f in os.listdir(os.path.join(frag_root, d)) if f.endswith(".c"))
        for f in files[d]:
            text = open(os.path.join(frag_root, d, f), errors="replace").read()
            for fn in entries:
                if fn not in owner and re.search(r"^[A-Za-z_][\w \t\*]*\b%s\s*\(" % fn, text, re.M):
                    owner[fn] = d
    used = sorted(set(owner.values()))
    index = {d: i for i, d in enumerate(used)}
    os.makedirs(os.path.join(out, "frag_sect"), exist_ok=True)
    cmake = ["# generated by tools/gen_frag_sections.py"]
    for d in used:
        k = index[d]
        hdr = os.path.join(out, "frag_sect", d + ".h")
        text = ('// generated by tools/gen_frag_sections.py: fragment "%s" keeps its writable data in its own sections\n'
                '#pragma clang section bss="__DATA,__fb%02d" data="__DATA,__fd%02d"\n' % (d, k, k))
        if not os.path.exists(hdr) or open(hdr).read() != text:
            open(hdr, "w").write(text)
        paths = " ".join('"${CMAKE_CURRENT_SOURCE_DIR}/game/src/fragments/%s/%s"' % (d, f) for f in files[d])
        cmake.append('set_source_files_properties(%s PROPERTIES COMPILE_OPTIONS "-include;%s")' % (paths, hdr))
    open(os.path.join(out, "frag_sections.cmake"), "w").write("\n".join(cmake) + "\n")
    c = ["// generated by tools/gen_frag_sections.py (see there)",
         "#include <mach-o/getsect.h>", "#include <mach-o/dyld.h>", "#include <stdint.h>", "#include <stdlib.h>",
         "#include <string.h>", "#include <stdio.h>", ""]
    for fn in sorted(owner):
        c.append("extern void %s();" % fn)
    c += ["", "struct PortFragSect { void* entry; const char* data; const char* bss; uint8_t* image; unsigned long size; };",
          "static struct PortFragSect sFragSects[] = {"]
    for fn in sorted(owner):
        k = index[owner[fn]]
        c.append('    { (void*)%s, "__fd%02d", "__fb%02d", NULL, 0 }, // %s' % (fn, k, k, owner[fn]))
    open(os.path.join(out, "frag_sections.txt"), "w").write("".join("%02d %s\n" % (index[d], d) for d in used))
    c += ["};", "",
          "static uint8_t* Sect(const char* name, unsigned long* size) {",
          "    return getsectiondata((const struct mach_header_64*)_dyld_get_image_header(0), \"__DATA\", name, size);",
          "}", "",
          "__attribute__((constructor)) static void PortFragSnapshot(void) {",
          "    for (size_t i = 0; i < sizeof(sFragSects) / sizeof(sFragSects[0]); i++) {",
          "        unsigned long n = 0;",
          "        uint8_t* p = Sect(sFragSects[i].data, &n);",
          "        if (p != NULL && n != 0) {",
          "            sFragSects[i].image = malloc(n);",
          "            memcpy(sFragSects[i].image, p, n);",
          "            sFragSects[i].size = n;",
          "        }",
          "    }",
          "}", "",
          "// Called when the game loads the fragment whose entry function is 'entry' (Fragment_Load).",
          "void Port_FragmentResetData(void* entry) {",
          "    static int off = -1;",
          "    if (off < 0) off = getenv(\"PORT_NO_FRAG_RESET\") != NULL;",
          "    if (off || entry == NULL) return;",
          "    for (size_t i = 0; i < sizeof(sFragSects) / sizeof(sFragSects[0]); i++) {",
          "        if (sFragSects[i].entry != entry) continue;",
          "        if (getenv(\"PORT_FRAG_RESET_SKIP\") && strstr(getenv(\"PORT_FRAG_RESET_SKIP\"), sFragSects[i].data)) return;",
          "        if (getenv(\"PORT_TRACE_FRAG_RESET\")) fprintf(stderr, \"[fragreset] %s\\n\", sFragSects[i].data);",
          "        unsigned long n = 0;",
          "        uint8_t* p = Sect(sFragSects[i].data, &n);",
          "        if (p != NULL && sFragSects[i].image != NULL && n == sFragSects[i].size) memcpy(p, sFragSects[i].image, n);",
          "        p = Sect(sFragSects[i].bss, &n);",
          "        if (p != NULL && n != 0) memset(p, 0, n);",
          "        return;",
          "    }",
          "}", ""]
    open(os.path.join(out, "frag_sections.c"), "w").write("\n".join(c))
    print("fragment sections: %d dirs" % len(used))


if __name__ == "__main__":
    main()
