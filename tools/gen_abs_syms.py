#!/usr/bin/env python3 -I
"""Emit absolute-symbol assembly for every symbol libstadium_game.a needs that the original linker
script defined as a constant (segment addresses D_<hex>, fragment/asset ROM boundaries, ...).
Values come from the decomp's linker map, so they are the ROM offsets / virtual addresses the
original build used. Leftover undefined names are written to build/leftover_syms.txt."""
import re, subprocess, pathlib, sys
root = pathlib.Path(__file__).resolve().parent.parent
# the unmodified decomp checkout and build the game is patched from (PORT_DECOMP_DIR, default ../pokestadium)
decomp = pathlib.Path(__import__("os").environ.get("PORT_DECOMP_DIR", root.parent / "pokestadium"))
mapfile = decomp / "build/pokestadium-us.map"
# C symbols carry a leading underscore in Mach-O (macOS) object files, not in ELF (Linux)
CPFX = "_" if __import__("sys").platform == "darwin" else ""
lib = root / "build/libstadium_game.a"
nm = subprocess.run(["nm", "-g", str(lib)], capture_output=True, text=True).stdout
undef, defd = set(), set()
for l in nm.splitlines():
    f = l.split()
    if len(f) == 2 and f[0] == "U": undef.add(f[1])
    elif len(f) == 3 and f[1] in "TDBSRC": defd.add(f[2])
need = sorted(s[len(CPFX):] for s in undef - defd if s.startswith(CPFX))
vals = {}
pat = re.compile(r"^\s+0x([0-9a-fA-F]{8,16})\s+([A-Za-z_]\w*)\s*(?:=.*)?$")
for l in mapfile.read_text(errors="replace").splitlines():
    m = pat.match(l)
    if m:
        vals.setdefault(m.group(2), int(m.group(1), 16))
# Only data-like linker constants become absolute symbols; code symbols (hasm functions, libultra
# internals) must get real implementations or stubs.
ABS_OK = re.compile(r"^(D_[0-9A-Fa-f]+(_\w+)?|\w+_(ROM_START|ROM_END|TEXT_START|TEXT_END|VRAM|VRAM_END)|\w*relocs\w*|F3DEX2_\w+|gAudioData|__binary_\w+|_?[0-9A-F]{5,6}_ROM_\w+)$")
out, left = [], []
for n in need:
    # named segment data (textures etc. at 0x0Nxxxxxx, a segment address) is as data-like as a D_ name
    if n in vals and vals[n] < 0x100000000 and (ABS_OK.match(n) or vals[n] < 0x10000000):
        out.append(f".globl SYM({n})\n.set SYM({n}), 0x{vals[n]:X}")
    else:
        left.append(n)
HEADER = ("// Generated by tools/gen_abs_syms.py from the decomp linker map.\n"
          "// SYM(): C symbol names carry a leading underscore in Mach-O (macOS), not in ELF (Linux) or 64-bit COFF (Windows).\n"
          "#if defined(__APPLE__)\n#define SYM(x) _##x\n#else\n#define SYM(x) x\n#endif\n")
(root / "src/port/generated/abs_syms.S").write_text(HEADER + "\n".join(out) + "\n")
(root / "build/leftover_syms.txt").write_text("\n".join(left) + "\n")
print(f"absolute: {len(out)}  leftover: {len(left)}")
